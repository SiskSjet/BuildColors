namespace Sisk.BuildColors.UI {

    /// <summary>
    /// Shared sizing constants.
    /// </summary>
    internal static class LayoutMetrics {
        /// <summary>
        /// Between parts of a single control, such as a checkbox and its label.
        /// </summary>
        public const float TIGHT_SPACING = 4f;

        /// <summary>
        /// Between rows that belong together.
        /// </summary>
        public const float ROW_SPACING = 8f;

        /// <summary>
        /// Between the sections of a pane.
        /// </summary>
        public const float SECTION_SPACING = 12f;

        /// <summary>
        /// Between the major blocks of a screen, such as the panes and the toolbar above them.
        /// </summary>
        public const float BLOCK_SPACING = 18f;

        public const float CONTENT_PADDING_X = 20f;
        public const float CONTENT_PADDING_Y = 16f;

        /// <summary>
        /// Inset of the content of a card from its own edge.
        /// </summary>
        public const float CARD_PADDING = 14f;

        public const float BUTTON_HEIGHT = 36f;
        public const float CHECKBOX_SIZE = 37f;
        public const float COLOR_PICKER_HEIGHT = 163f;
        public const float CONDITION_SECTION_HEIGHT = 300f;
        public const float CONTROL_HEIGHT = 40f;
        public const float HEADING_HEIGHT = 30f;
        public const float LABEL_HEIGHT = 26f;
        public const float SEPARATOR_HEIGHT = .75f;
        public const float STATUS_HEIGHT = 24f;
    }
}
